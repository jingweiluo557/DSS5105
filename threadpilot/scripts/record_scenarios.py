"""Record the conversation scenarios in docs/conversation_scenarios.md by running the real dashboard chat.

The transcripts in that page are not written by hand: this script opens the demo page in headless Chromium, asks the scripted
questions and writes down what the chat answered. A test (tests/test_scenarios_doc.py) re-records and compares, so the page
cannot drift from the behaviour.

    pip install -r requirements-dev.txt && python -m playwright install chromium
    python scripts/record_scenarios.py            # rewrite the generated part of docs/conversation_scenarios.md
    python scripts/record_scenarios.py --check    # exit 1 if the page is out of date (what the test does)

Everything above the START marker and below the END marker in the page is hand-written and left alone.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "conversation_scenarios.md"
DEMO = ROOT / "demo" / "briefing_demo.html"
START = "<!-- scenarios:start (generated by scripts/record_scenarios.py, do not edit by hand) -->"
END = "<!-- scenarios:end -->"

MORNING = 8        # Thursday 9 April 2026, "simulated day 8": data up to Wednesday 8 April

# Each step is ("ask", question), ("confirm",) to press Confirm on the last card, or ("go", morning) to move the date.
SCENARIOS = [
    {"id": "S1", "title": "The morning summary, then \"why?\"",
     "shows": "Three lines first; the detail and the rows behind them one question away (tracing).",
     "steps": [("ask", "Did anything go wrong yesterday?"), ("ask", "Why is ORD-120 late?")]},
    {"id": "S2", "title": "A vague question: ask, do not guess",
     "shows": "\"The TrendCart order\" could be any of six orders, so the co-pilot asks which one before it answers.",
     "steps": [("ask", "How is the TrendCart order doing?"), ("ask", "ORD-020")]},
    {"id": "S3", "title": "Follow-ups that depend on the previous turn",
     "shows": "Multi-turn memory: \"it\" and short questions without a name refer to the order just discussed.",
     "steps": [("ask", "What is the status of ORD-120?"), ("ask", "when is it due?"), ("ask", "who is the customer?"),
               ("ask", "how many pieces?"), ("ask", "is it late?"), ("ask", "should we expedite it?")]},
    {"id": "S4", "title": "Questions the data cannot answer",
     "shows": "A refusal that names what is missing beats a plausible number. Where the data has part of the answer, it gives that part and "
              "says what it cannot know.",
     "steps": [("ask", "What's our revenue this month?"), ("ask", "Who is the best machine operator?"),
               ("ask", "Why did washing drop yesterday?"), ("ask", "What will demand be next month?")]},
    {"id": "S5", "title": "Feasibility: an estimate with assumptions, never a plain yes",
     "shows": "A date range, the bottleneck and the assumptions; a missing date is asked for; a follow-up changes one input.",
     "steps": [("ask", "Can we take 800 hoodies by the 25th?"), ("ask", "What about 400 pieces?"),
               ("ask", "Can we take 800 hoodies?"), ("ask", "by the 25th")]},
    {"id": "S6", "title": "Actions: preview, confirm, log",
     "shows": "Nothing with a side effect happens before the card is confirmed, the card states the worst case, and what the co-pilot "
              "cannot do is refused plainly.",
     "steps": [("ask", "Chase ORD-120"), ("confirm",), ("ask", "Add a note to ORD-120: waiting for the customer's trims"), ("confirm",),
               ("ask", "Delete ORD-005")]},
    {"id": "S7", "title": "A watch that fires on its own",
     "shows": "A standing check is set up with a confirmation, then evaluated by the next morning's briefing without being asked.",
     "steps": [("ask", "Tell me if ORD-120 hasn't moved by Friday"), ("confirm",), ("go", MORNING + 1)]},
    {"id": "S8", "title": "A reminder that clears itself",
     "shows": "When the condition is no longer true the next morning, the reminder says so instead of raising a false alarm.",
     "steps": [("ask", "Remind me tomorrow if packing is still behind"), ("confirm",), ("go", MORNING + 1)]},
    {"id": "S9", "title": "Stage output and follow-ups",
     "shows": "\"Normal\" is the previous 8 same weekdays; follow-ups keep the stage and change one thing.",
     "steps": [("ask", "How did packing do yesterday?"), ("ask", "and washing?"), ("ask", "what about on Monday?")]},
]

JS = """async ([morning, steps]) => {
  const C = ThreadPilotChat, out = []; let last = null;
  go(morning); C.reset();
  for (const s of steps) {
    if (s[0] === "ask") {
      const r = C.respond(s[1]); last = r;
      out.push({kind: "ask", q: s[1], lines: r.lines, asks: !!r.asks, refused: !!r.refused, intent: r.intent,
        tools: [...new Set((r.tools || []).map(t => t.name))], sources: (r.sources || []).slice(0, 2),
        chips: (r.chips || []).map(c => c.label), has_detail: !!r.detail,
        confirm: r.confirm ? {title: r.confirm.title, blast: r.confirm.blast, fields: (r.confirm.fields || []).map(f => [f.label, f.value])} : null});
    } else if (s[0] === "confirm") {
      out.push({kind: "confirm", done: last && last.confirm ? C.apply(last, {}) : null});
    } else if (s[0] === "go") {
      go(s[1]);
      out.push({kind: "go", day: document.querySelector("h1, .greeting, #greeting") ? document.querySelector("h1, .greeting, #greeting").textContent.trim() : "",
        watches: C.watches.map(w => ({state: w.state, text: w.text, result: w.result}))});
    }
  }
  return out;
}"""


CLOCK = re.compile(r"\b(?:[01]\d|2[0-3]):[0-5]\d\b(?! briefing)")      # "Logged at 22:42" depends on when the test runs


def mask_clock(text: str) -> str:
    return CLOCK.sub("HH:MM", text)


def record(page) -> str:
    """Run every scenario on an open demo page and return the generated markdown."""
    parts: list[str] = []
    for sc in SCENARIOS:
        steps = [list(s) for s in sc["steps"]]
        res = page.evaluate(JS, [MORNING, steps])
        parts.append(f"### {sc['id']}. {sc['title']}\n\n*{sc['shows']}*\n")
        for r in res:
            if r["kind"] == "ask":
                parts.append(f"> **You:** {r['q']}  ")
                body = " ".join(line.strip() for line in r["lines"])
                parts.append(f"> **ThreadPilot:** {body}  ")
                notes = []
                if r["confirm"]:
                    fields = "; ".join(f"{k}: {v}" for k, v in r["confirm"]["fields"])
                    notes.append(f"confirmation card \"{r['confirm']['title']}\"" + (f" ({fields})" if fields else "")
                                 + f". {r['confirm']['blast']}")
                if r["asks"]:
                    notes.append("asks a question instead of answering")
                if r["refused"]:
                    notes.append("declines: nothing is invented and nothing is changed")
                if r["chips"] and not r["refused"] and not r["confirm"]:
                    notes.append("suggested next questions: " + " | ".join(r["chips"][:3]))
                if r["has_detail"]:
                    notes.append("\"Show detail\" opens the rows behind it")
                if r["sources"]:
                    notes.append("sources: " + "; ".join(r["sources"]))
                if r["tools"]:
                    notes.append("tools: " + ", ".join(r["tools"]))
                if notes:
                    parts.append("> <sub>" + " · ".join(notes) + "</sub>")
                parts.append("")
            elif r["kind"] == "confirm":
                parts.append(f"> **You:** *(presses Confirm)*  \n> **ThreadPilot:** {r['done']}\n")
            else:
                ws = "; ".join(f"{w['state']}: {w['text']}" + (f" ({w['result']})" if w["result"] else "") for w in r["watches"]) or "no watches"
                parts.append(f"> *The date moves on to the next morning's briefing.* Watches now: {ws}\n")
    return mask_clock("\n".join(parts).rstrip() + "\n")


def render_doc(generated: str) -> str:
    """Splice the generated transcripts between the markers of the hand-written page."""
    text = DOC.read_text(encoding="utf-8")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n\n{generated}\n{END}{tail}"


def open_demo(playwright):
    browser = playwright.chromium.launch()
    page = browser.new_page()
    page.goto(DEMO.as_uri())
    page.wait_for_selector("#riskCard .rk-col")
    return browser, page


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/conversation_scenarios.md is out of date")
    args = ap.parse_args()
    from playwright.sync_api import sync_playwright
    with sync_playwright() as p:
        browser, page = open_demo(p)
        try:
            new = render_doc(record(page))
        finally:
            browser.close()
    if args.check:
        ok = DOC.read_text(encoding="utf-8") == new
        print("conversation_scenarios.md is up to date" if ok else "conversation_scenarios.md is OUT OF DATE: run python scripts/record_scenarios.py")
        return 0 if ok else 1
    DOC.write_text(new, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
