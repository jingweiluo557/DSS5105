"""Record the boundary table in docs/tool_boundaries.md by running the real dashboard chat.

Each case is a question whose answer could plausibly come from two different tools. The case says which tool must answer
and which neighbour must NOT, and this script fails if the chat does anything else. So the table in the page is not a claim
about the design: it is what the chat did, on the day the page was written, and a test (tests/test_tool_boundaries_doc.py)
re-runs it so the page cannot drift.

    python scripts/record_boundaries.py            # rewrite the generated part of docs/tool_boundaries.md
    python scripts/record_boundaries.py --check    # exit 1 if the page is out of date (what the test does)

Everything outside the START and END markers is hand-written and left alone.
"""
from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "tool_boundaries.md"
START = "<!-- boundaries:start (generated by scripts/record_boundaries.py, do not edit by hand) -->"
END = "<!-- boundaries:end -->"
MORNING = 8     # Thursday 9 April 2026, the same simulated morning as the conversation scenarios


def _scenarios():
    spec = importlib.util.spec_from_file_location("record_scenarios", ROOT / "scripts" / "record_scenarios.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# group, the question, the tool(s) that must answer, the neighbour that must not, and why the line is drawn there.
# "ask" marks a case where the right behaviour is a question back, "refuse" one where it is a plain no, "confirm" one that
# opens a confirmation card instead of acting.
CASES = [
    ("Facts that look alike", [
        dict(q="What is the status of ORD-120?", tools=["get_order"], not_=["trace_order"],
             why="A status is a fact. Why it is flagged is a separate question with a separate tool."),
        dict(q="Why is ORD-120 late?", tools=["trace_order"], not_=["get_order"],
             why="'Why' goes back to the rows (queue position, findings, source line) instead of repeating the status."),
        dict(q="Which orders are late?", tools=["list_orders"], not_=["list_by_risk"],
             why="Late means already past the due date: a fact. A risk level is a projection and has its own tool."),
        dict(q="Which orders are high risk?", tools=["list_by_risk"], not_=["list_orders"],
             why="High risk is a projection under stated assumptions, never a promise, so it is kept apart from 'late'."),
        dict(q="How is TrendCart doing?", tools=["list_orders", "get_customer"], not_=["list_findings"],
             why="One named customer: its orders and its on-time record. No ranking is implied."),
        dict(q="Which customers are in trouble?", tools=["list_customers"], not_=["get_customer"],
             why="Many customers at once is a list; one customer is a lookup."),
    ]),
    ("Discovery is not retrieval", [
        dict(q="Did anything go wrong yesterday?", tools=["get_briefing_summary"], not_=["list_findings"],
             why="The three-line summary comes first; the ranked findings are one follow-up away."),
        dict(q="What needs my attention?", tools=["list_findings"], not_=["list_orders"],
             why="A finding can be a stage, a customer or a group of orders. A list of orders cannot say that."),
        dict(q="Which orders are stuck?", tools=["list_orders"], not_=["list_findings"],
             why="Idle orders are a plain filter (5+ working days with no activity). It does not say whether the queue explains it."),
        dict(q="Which customer is stalled?", tools=["list_findings"], not_=["list_orders", "list_customers"],
             why="A customer whose every order has stopped, while later-due orders moved past, is a finding. Found before this page was "
                 "written: the chat used to answer with the idle-order list."),
    ]),
    ("Judgement needs a stated rule", [
        dict(q="How did packing do yesterday?", tools=["get_stage_output"], not_=["get_target_status"],
             why="'Normal' is the mean of the previous 8 same weekdays with a band. A target is a number the manager sets."),
        dict(q="Are any stages missing their target?", tools=["get_target_status"], not_=["get_stage_output"],
             why="A target is the manager's own, set in Settings. No target set means it says so."),
        dict(q="Is 800 pieces from assembly normal?", tools=["get_stage_output"], not_=["explain_no_data"],
             why="The brief's own example. The manager's number is judged against the band and marked 'not checked'. Found before this "
                 "page was written: the chat ignored the 800 and reported yesterday's record."),
        dict(q="Why did washing drop yesterday?", tools=["get_stage_output"], not_=["explain_no_data"],
             why="The size of the drop is in the data, so it is given. The cause is not, so the reply says it cannot say why."),
        dict(q="Where is the bottleneck?", tools=["get_pipeline"], not_=["get_stage_output"],
             why="Where work is queued, not how much a stage made."),
        dict(q="Can we take 800 hoodies by the 25th?", tools=["check_feasibility"], not_=["get_pipeline", "get_forecast"],
             why="An estimate with assumptions, built on the queue and recent arrivals. Never a plain yes."),
        dict(q="What orders do we expect next week?", tools=["get_forecast"], not_=["check_feasibility"],
             why="What is coming is a forecast of orders. Whether one specific order fits is feasibility."),
    ]),
    ("Reading is never acting", [
        dict(q="Should we expedite ORD-120?", tools=["assess_expedite"], not_=["draft_chase"], confirm=False,
             why="A recommendation with its cost to other orders. It changes nothing. A stalled order gets 'find the blocker first'."),
        dict(q="Chase ORD-120", tools=["draft_chase"], not_=["assess_expedite"], confirm=True,
             why="A draft plus a confirmation card with the worst case. Nothing is sent until the manager confirms."),
        dict(q="Add a note to ORD-120: waiting for trims", tools=["add_note"], not_=["draft_chase"], confirm=True,
             why="A note is a record, not a message. Same gate."),
        dict(q="Tell me if ORD-120 hasn't moved by Friday", tools=["create_watch"], not_=["add_note"], confirm=True,
             why="A standing check that fires on its own. Created only after confirmation."),
    ]),
    ("Where the tools stop", [
        dict(q="What's our revenue this month?", tools=["explain_no_data"], not_=["get_forecast"], refuse=True,
             why="No prices exist in the data. A plain no beats a plausible figure."),
        dict(q="What will demand be next month?", tools=["explain_no_data"], not_=["get_forecast"], refuse=True,
             why="The forecast covers two weeks. Past that the tool declines instead of stretching."),
        dict(q="Who is the best worker?", tools=["explain_no_data"], not_=["get_stage_output"], refuse=True,
             why="Output is recorded per stage per day, not per person."),
        dict(q="Delete ORD-005", tools=["explain_no_data"], not_=["add_note", "draft_chase"], refuse=True,
             why="No tool can change or remove an order. The refusal says so and nothing is changed."),
    ]),
    ("When the right move is a question", [
        dict(q="How is the TrendCart order doing?", tools=["list_orders"], not_=["get_order"], ask=True,
             why="TrendCart has six orders in progress. Picking one would answer about the wrong order."),
        dict(q="Is it late?", tools=[], not_=["get_order", "list_orders"], ask=True,
             why="'It' with nothing before it. The chat asks which order instead of guessing."),
    ]),
]

JS = """async ([morning, q]) => {
  go(morning); ThreadPilotChat.reset();
  const r = ThreadPilotChat.respond(q);
  return {intent: r.intent, lines: r.lines, tools: [...new Set((r.tools || []).map(t => t.name))],
          asks: !!r.asks, refused: !!r.refused, confirm: !!r.confirm};
}"""


def run_cases(page) -> list[tuple[str, list[dict]]]:
    """Ask every question in a fresh conversation and check the chat did what the case says. Raises AssertionError otherwise."""
    out = []
    for group, cases in CASES:
        rows = []
        for c in cases:
            r = page.evaluate(JS, [MORNING, c["q"]])
            got = set(r["tools"])
            assert got == set(c["tools"]), f"{c['q']!r}: the chat used {sorted(got)}, the case says {sorted(c['tools'])}"
            assert not (got & set(c["not_"])), f"{c['q']!r}: used {sorted(got & set(c['not_']))}, which this case says it must not"
            assert r["asks"] == bool(c.get("ask")), f"{c['q']!r}: asks={r['asks']}"
            assert r["refused"] == bool(c.get("refuse")), f"{c['q']!r}: refused={r['refused']}"
            assert r["confirm"] == bool(c.get("confirm")), f"{c['q']!r}: confirmation card={r['confirm']}"
            rows.append({**c, "intent": r["intent"], "first": r["lines"][0].strip()})
        out.append((group, rows))
    return out


def render(page) -> str:
    sc = _scenarios()
    parts = []
    for group, rows in run_cases(page):
        parts.append(f"### {group}\n")
        parts.append("| The manager asks | Tools called | Not | What happened | Why the line is here |")
        parts.append("| --- | --- | --- | --- | --- |")
        for r in rows:
            kind = "asks back" if r.get("ask") else "declines" if r.get("refuse") else "confirmation card, nothing happens yet" if r.get("confirm") else ""
            tools = ", ".join(f"`{t}`" for t in r["tools"]) or "none"
            nots = ", ".join(f"`{t}`" for t in r["not_"])
            first = r["first"].replace("|", "/")
            parts.append(f"| {r['q']} | {tools} | {nots} | {first}{' *(' + kind + ')*' if kind else ''} | {r['why']} |")
        parts.append("")
    return sc.mask_clock("\n".join(parts).rstrip() + "\n")


def render_doc(generated: str) -> str:
    text = DOC.read_text(encoding="utf-8")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n\n{generated}\n{END}{tail}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/tool_boundaries.md is out of date")
    args = ap.parse_args()
    from playwright.sync_api import sync_playwright
    sc = _scenarios()
    with sync_playwright() as p:
        browser, page = sc.open_demo(p)
        try:
            new = render_doc(render(page))
        finally:
            browser.close()
    if args.check:
        ok = DOC.read_text(encoding="utf-8") == new
        print("tool_boundaries.md is up to date" if ok else "tool_boundaries.md is OUT OF DATE: run python scripts/record_boundaries.py")
        return 0 if ok else 1
    DOC.write_text(new, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
